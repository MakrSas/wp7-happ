#!/usr/bin/env python3
"""
Замена MarkupCompilePass1 из Windows Phone SDK: по XAML генерирует *.g.cs с полями x:Name
и InitializeComponent(), как это делает Visual Studio.

  gen_g.py <assembly> <outdir> <base_dir> file.xaml...
"""
import os
import sys
import xml.etree.ElementTree as ET

X = "http://schemas.microsoft.com/winfx/2006/xaml"
PRESENTATION = "http://schemas.microsoft.com/winfx/2006/xaml/presentation"

# Элементы пространства по умолчанию (Silverlight 4).
DEFAULT_TYPES = {
    "System.Windows": "Application ResourceDictionary DataTemplate Style Setter",
    "System.Windows.Controls": "Grid StackPanel Canvas Border TextBlock TextBox PasswordBox Button CheckBox "
                               "RadioButton Slider ScrollViewer ListBox ListBoxItem ContentControl ContentPresenter "
                               "Image ProgressBar HyperlinkButton ItemsControl UserControl ColumnDefinition RowDefinition "
                               "MediaElement Viewbox WrapPanel",
    "System.Windows.Shapes": "Rectangle Ellipse Path Line Polygon Polyline",
    "System.Windows.Documents": "Run LineBreak",
    "System.Windows.Media": "SolidColorBrush ImageBrush LinearGradientBrush",
    "System.Windows.Media.Animation": "Storyboard DoubleAnimation",
}
DEFAULT_MAP = {name: ns for ns, names in DEFAULT_TYPES.items() for name in names.split()}


def clr_namespaces(path):
    """prefix → URI из xmlns:..., ElementTree их не отдаёт, читаем руками."""
    out = {}
    for event, (prefix, uri) in ET.iterparse(path, events=["start-ns"]):
        out[uri] = prefix
    return out


def type_of(tag):
    uri, local = tag[1:].split("}", 1)
    if uri == PRESENTATION:
        if local not in DEFAULT_MAP:
            raise SystemExit("gen_g: неизвестный тип <%s> — добавьте в DEFAULT_TYPES" % local)
        return DEFAULT_MAP[local] + "." + local
    if uri.startswith("clr-namespace:"):
        ns = uri[len("clr-namespace:"):].split(";", 1)[0]
        return ns + "." + local
    raise SystemExit("gen_g: пространство %s не поддерживается" % uri)


def main():
    asm, outdir, base = sys.argv[1], sys.argv[2], sys.argv[3]
    os.makedirs(outdir, exist_ok=True)
    for path in sys.argv[4:]:
        root = ET.parse(path).getroot()
        cls = root.get("{%s}Class" % X)
        if not cls:
            continue
        ns, name = cls.rsplit(".", 1)
        base_type = type_of(root.tag)
        fields = []
        for el in root.iter():
            n = el.get("{%s}Name" % X) or (el.get("Name") if el is not root else None)
            if n and el is not root:
                fields.append((type_of(el.tag), n))
        rel = os.path.relpath(path, base).replace(os.sep, "/")
        lines = [
            "// <auto-generated> tools/gen_g.py из %s </auto-generated>" % rel,
            "namespace %s {" % ns,
            "    public partial class %s : %s {" % (name, base_type),
        ]
        for t, n in fields:
            lines.append("        internal %s %s;" % (t, n))
        lines += [
            "        private bool _contentLoaded;",
            "        [System.Diagnostics.DebuggerNonUserCode]",
            "        public void InitializeComponent() {",
            "            if (_contentLoaded) return;",
            "            _contentLoaded = true;",
            '            System.Windows.Application.LoadComponent(this, new System.Uri("/%s;component/%s", System.UriKind.Relative));'
            % (asm, rel),
        ]
        for t, n in fields:
            lines.append('            this.%s = (%s)this.FindName("%s");' % (n, t, n))
        lines += ["        }", "    }", "}", ""]
        out = os.path.join(outdir, rel.replace("/", "_") + ".g.cs")
        with open(out, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))
        print("gen_g:", rel, "→", len(fields), "полей")


if __name__ == "__main__":
    main()
